/**
 * @file worker.validation.js
 * @description Zod request-validation schemas for the DispatchIQ Worker
 * Management API.
 *
 * These schemas validate and normalize pagination, worker lifecycle filters,
 * and worker identifiers before requests reach controllers and services.
 *
 * Worker lifecycle values intentionally mirror the WorkerStatus enum defined
 * by the persistence layer. Clients cannot submit arbitrary status strings.
 */

import { z } from 'zod';

const WORKER_STATUSES = Object.freeze([
  'STARTING',
  'ONLINE',
  'BUSY',
  'UNHEALTHY',
  'OFFLINE',
  'STOPPING',
]);

/**
 * Validates worker-list query parameters.
 *
 * Pagination values are coerced from HTTP query strings into numbers.
 * Unknown query properties are stripped by Zod's object behavior so only
 * supported filtering options reach downstream layers.
 *
 * @type {import('zod').ZodType}
 */
export const listWorkersQuerySchema = z.object({
  page: z.coerce.number().int().positive().default(1),

  limit: z.coerce.number().int().positive().max(100).default(20),

  status: z.enum(WORKER_STATUSES).optional(),
});

/**
 * Validates the worker identifier supplied through route parameters.
 *
 * WorkerInstance IDs are UUID values generated by Prisma, so rejecting invalid
 * identifiers at the HTTP boundary avoids unnecessary database queries.
 *
 * @type {import('zod').ZodType}
 */
export const workerIdParamsSchema = z.object({
  workerId: z.string().uuid('Worker ID must be a valid UUID.'),
});
